ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"


def _token() -> str:
    """A capiss-sized base64url token (capiss tokens are 600 characters or more)."""
    return secrets.token_urlsafe(480)


def _run(length: int, distinct: int) -> str:
    return "".join(ALPHABET[i % distinct] for i in range(length))


def _ed25519_pem() -> bytes:
    return ed25519.Ed25519PrivateKey.generate().private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())


def _der_b64(key) -> str:
    der = key.private_bytes(serialization.Encoding.DER, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    return base64.b64encode(der).decode("ascii")


def _certificate_pem() -> str:
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "svid")])
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
            .serial_number(1).not_valid_before(now).not_valid_after(now + datetime.timedelta(hours=1))
            .add_extension(x509.SubjectAlternativeName([x509.UniformResourceIdentifier("spiffe://varambu.org/agent-a")]), False)
            .sign(key, hashes.SHA256()))
    return cert.public_bytes(serialization.Encoding.PEM).decode("ascii")


def _kinds(text: str) -> set[str]:
    return {f.kind for f in es.scan_text(text, "fixture.txt")}


# --- each secret shape fails --------------------------------------------------

SECRET_FIXTURES = {
    "token in a text file": lambda: (_token() + "\n", "token-shaped value"),
    "token in a JSON field": lambda: (json.dumps({"token": _token(), "expires_at": 1}), "token-shaped value"),
    "PEM private key block": lambda: (_ed25519_pem().decode("ascii"), "PEM private key"),
    "capiss root_key.pem (PKCS#8 PEM)": lambda: ("cat root_key.pem\n" + _ed25519_pem().decode("ascii"), "PEM private key"),
    "base64 of root_key.pem in text": lambda: (base64.b64encode(_ed25519_pem()).decode("ascii") + "\n",
                                               "base64-encoded PEM private key"),
    "base64 of root_key.pem in JSON": lambda: (json.dumps({"blob": base64.b64encode(_ed25519_pem()).decode("ascii")}),
                                               "base64-encoded PEM private key"),
    "base64 PKCS#8 DER Ed25519 key in JSON": lambda: (json.dumps({"private_key": _der_b64(ed25519.Ed25519PrivateKey.generate())}),
                                                      "base64 PKCS#8 private key"),
    "base64 PKCS#8 DER EC P-256 key in JSON": lambda: (json.dumps({"private_key": _der_b64(ec.generate_private_key(ec.SECP256R1()))}),
                                                       "base64 PKCS#8 private key"),
    "JIRA_API_TOKEN line": lambda: ("JIRA_API_TOKEN=" + secrets.token_hex(12) + "\n", "credential line"),
    "Authorization Bearer header": lambda: ("Authorization: Bearer " + secrets.token_hex(16) + "\n", "credential line"),
    "Atlassian API token": lambda: ("token ATATT3x" + secrets.token_urlsafe(30) + "\n", "Atlassian API token"),
}


@pytest.mark.parametrize("name", sorted(SECRET_FIXTURES))
def test_each_secret_shape_is_found(name: str) -> None:
    text, kind = SECRET_FIXTURES[name]()
    assert kind in _kinds(text)


@pytest.mark.parametrize("name", sorted(SECRET_FIXTURES))
def test_finding_names_file_and_kind_never_the_value(name: str, tmp_path: Path) -> None:
    text, kind = SECRET_FIXTURES[name]()
    path = tmp_path / "evidence.txt"
    path.write_text(text, encoding="utf-8")
    findings, errors = es.scan([tmp_path])
    assert errors == []
    rendered = "\n".join(str(f) for f in findings)
    assert str(path) in rendered and kind in rendered
    for secret_part in (text.strip()[-24:], text.strip()[:24]):
        if len(secret_part.strip()) >= 16 and not secret_part.startswith(("cat ", "-----", "JIRA_API", "Authoriz", "token ", '{"')):
            assert secret_part not in rendered


