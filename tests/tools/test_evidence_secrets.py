# --- publishing replaces token values with fingerprints ------------------------

def test_publish_replaces_tokens_with_fingerprints(tmp_path: Path) -> None:
    token = _token()
    cert = _certificate_pem()
    scratch = tmp_path / "scratch"
    (scratch / "sub").mkdir(parents=True)
    (scratch / "token.txt").write_text(token + "\n")
    (scratch / "mint.json").write_text(json.dumps({"token": token, "expires_at": 5}))
    (scratch / "svid.pem").write_text(cert)
    (scratch / "sub" / "binary.bin").write_bytes(b"\x00\xff\xfe" + token.encode() + b"\x00")
    (scratch / "outcome_1.txt").write_text("status=403 reason=sub_mismatch\n")
    published = tmp_path / "published"
    es.publish(scratch, published)
    fp = es.fingerprint(token)
    assert (published / "token.txt").read_text() == fp + "\n"
    assert json.loads((published / "mint.json").read_text()) == {"token": fp, "expires_at": 5}
    assert (published / "svid.pem").read_text() == cert
    assert (published / "sub" / "binary.bin").read_bytes() == b"\x00\xff\xfe" + fp.encode() + b"\x00"
    assert (published / "outcome_1.txt").read_text() == "status=403 reason=sub_mismatch\n"
    assert es.scan([published]) == ([], [])


def test_publish_cli_and_same_token_same_fingerprint(tmp_path: Path) -> None:
    token = _token()
    scratch = tmp_path / "scratch"
    scratch.mkdir()
    (scratch / "a.txt").write_text(token)
    (scratch / "b.json").write_text(json.dumps({"token": token}))
    published = tmp_path / "published"
    subprocess.run([sys.executable, str(ROOT / "scripts" / "evidence_secrets.py"), "publish", str(scratch), str(published)],
                   check=True)
    assert (published / "a.txt").read_text() == json.loads((published / "b.json").read_text())["token"]
    assert token not in (published / "a.txt").read_text()


