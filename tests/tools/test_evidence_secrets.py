# --- the check reads only the publication set, and fails closed ----------------

def test_scan_opens_no_file_outside_the_publication_set(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    published = tmp_path / "published"
    (published / "rogue-tests" / "M1-T1_x").mkdir(parents=True)
    (published / "rogue-tests" / "M1-T1_x" / "outcome_1.txt").write_text("ok\n")
    report = published / "test_report.log"
    report.write_text("PASS\n")
    (tmp_path / "secret_store").write_text(_ed25519_pem().decode("ascii"))
    opened: list[Path] = []
    real_open = builtins.open

    def recording_open(file, *args, **kwargs):
        opened.append(Path(file).resolve())
        return real_open(file, *args, **kwargs)

    monkeypatch.setattr(builtins, "open", recording_open)
    findings, errors = es.scan([report, published / "rogue-tests"])
    monkeypatch.undo()
    assert findings == [] and errors == []
    assert opened, "the check opened no file"
    assert all(path.is_relative_to(published.resolve()) for path in opened), opened


@pytest.mark.skipif(os.geteuid() == 0, reason="root reads files regardless of mode")
def test_unreadable_file_fails_closed(tmp_path: Path) -> None:
    path = tmp_path / "evidence.txt"
    path.write_text("ok\n")
    path.chmod(0)
    try:
        findings, errors = es.scan([tmp_path])
    finally:
        path.chmod(0o600)
    assert findings == []
    assert errors and str(path) in errors[0]


# --- qa-evidence checks the whole publication set ------------------------------

def _evidence_layout(tmp_path: Path) -> Path:
    """A minimal passing run: one suite, one prefix, all guard artifacts, a PASS line."""
    (tmp_path / "trace").mkdir()
    (tmp_path / "trace" / "tests.yaml").write_text(
        "tests:\n  - id: E2E-SUITE-X\n    type: e2e_suite\n    evidence_prefixes: [M1-T1]\n", encoding="utf-8")
    evdir = tmp_path / "artifacts" / "rogue-tests" / "M1-T1_case"
    evdir.mkdir(parents=True)
    for name in ("premise_1.txt", "exercise_1.txt", "outcome_1.txt", "cmd_premise_1.txt"):
        (evdir / name).write_text("ok\n")
    (tmp_path / "artifacts" / "quality").mkdir()
    (tmp_path / "test_report.log").write_text(
        "EVIDENCE_DIR=/tmp/rogue-tests/M1-T1_case\n[T1] case .... PASS\nTotal: 1  Passed: 1  Failed: 0\n", encoding="utf-8")
    return tmp_path


def _qa_evidence(root: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "validate_e2e_evidence.py"), "--tests", "trace/tests.yaml",
         "--evidence-dir", "artifacts/rogue-tests", "--test-report", "test_report.log",
         "--report-json", "artifacts/quality/evidence_report.json",
         "--publication-set", "test_report.log", "artifacts/rogue-tests", "artifacts/quality"],
        cwd=root, capture_output=True, text=True, check=False)


def test_qa_evidence_passes_a_clean_run(tmp_path: Path) -> None:
    result = _qa_evidence(_evidence_layout(tmp_path))
    assert result.returncode == 0, result.stderr


@pytest.mark.parametrize("where", ["evidence text file", "test_report.log", "quality JSON"])
def test_qa_evidence_fails_on_a_token_anywhere_in_the_publication_set(tmp_path: Path, where: str) -> None:
    root = _evidence_layout(tmp_path)
    token = _token()
    target = {
        "evidence text file": root / "artifacts" / "rogue-tests" / "M1-T1_case" / "token.txt",
        "test_report.log": root / "test_report.log",
        "quality JSON": root / "artifacts" / "quality" / "other_report.json",
    }[where]
    if where == "quality JSON":
        target.write_text(json.dumps({"token": token}))
    else:
        with open(target, "a", encoding="utf-8") as handle:
            handle.write(token + "\n")
    result = _qa_evidence(root)
    assert result.returncode == 1
    assert "token-shaped value" in result.stderr and str(target.relative_to(root)) in result.stderr
    assert token not in result.stdout + result.stderr
    report = (root / "artifacts" / "quality" / "evidence_report.json").read_text()
    assert token not in report


